// Infantry weapon definitions: real-world data for the guns used in Heroes &
// Generals. Reload times and the number of spare magazines follow the original
// game's data (they were realistic); everything about how bullets fly comes from
// the real ammunition (ammo.js) and the physics engine.
//
// Fields:
//   type     rifle | semi | carbine | smg | assault | lmg | pistol | revolver | sniper | atRifle | launcher | grenade | melee
//   feed     how it is loaded: box (detachable magazine), drum, pan, belt, enbloc (M1 Garand
//            clip), stripper (internal magazine filled from 5-round clips or single rounds),
//            gate (revolver loaded one round at a time), moon (revolver half-moon clips),
//            single (one round/rocket at a time), disposable
//   capacity magazine capacity; reserve = spare magazines/clips carried
//   modes    fire modes in the order the selector cycles: semi, auto, slow (BAR slow auto), bolt
//   rpm      cyclic rate (rounds per minute)
//   openBolt fires from an open bolt (most SMGs and MGs): no round waits in the chamber
//   holdOpen bolt locks back after the last round (faster reload)
//   sight    { kind: notch | aperture | post | scope, unit: m | yd, ranges: [...], zero }
//   accuracy mechanical accuracy in MOA (minutes of angle) with service ammunition
//   hipError typical pointing error when firing from the hip (degrees)
//   mass     empty weight (kg); loadedMass is computed
//
// Scoped rifles are made from a rifle and a scope in scopes.js (FITTINGS), with
//   base     the rifle it is built on (its id)
//   scope    { name, mag, reticle, fieldDeg, eyeRelief } of the scope
//   irons    the rifle's own sight, when it can still be used beside the scope
//   clipsBlocked  the scope covers the clip guide: loaded one round at a time
