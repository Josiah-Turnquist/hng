// Fill in derived values once.
for (const [id, w] of Object.entries(WEAPONS)) {
  w.id = id;
  w.model = w.model || id;
  if (w.type === 'grenade') {
    w.sight = { kind: 'none', unit: 'm', ranges: [0], zero: 0 };
    w.modes = ['semi'];
    w.feed = 'grenade';
    w.rpm = 60;
    w.reload = {};
  }
  if (w.type === 'melee') {
    // A close-combat weapon fires nothing: what the rest of the game reads off
    // a gun (sights, fire modes, magazine) is there but empty. Its blows are
    // game/melee.js's.
    w.sight = { kind: 'none', unit: 'm', ranges: [0], zero: 0 };
    w.modes = ['semi'];
    w.feed = 'melee';
    w.capacity = 0;
    w.reserve = 0;
    w.reload = {};
    w.rpm = 60 / w.attack.period;
    w.loadedMass = w.mass;
    continue;
  }
  if (w.type === 'binoculars') {
    // Nothing to fire or load: a sight with no settings, an empty magazine.
    w.sight = { kind: 'scope', unit: 'm', ranges: [0], zero: 0 };
    w.modes = ['semi'];
    w.feed = 'none';
    w.rpm = 60;
    w.reload = {};
    w.capacity = 0;
    w.reserve = 0;
    w.accuracy = 0;
    w.hipError = 0;
    w.ammoData = null;
    w.loadedMass = w.mass;
    continue;
  }
  const a = AMMO[w.ammo];
  if (!a) throw new Error(`weapon ${id}: unknown ammo ${w.ammo}`);
  w.ammoData = a;
  // Rough loaded weight: gun + one loaded magazine/clip.
  w.loadedMass = w.mass + w.capacity * (a.mass + (a.powder || 0) + a.mass * 1.2);
}

